/*
 * What the sequence does, for the reader who has to debug it (register names
 * from the OV2640 datasheet; 0xFF = RA_DLMT selects the DSP (0x00) or sensor
 * (0x01) bank, so the same address means different things above and below it):
 *
 *   - sensor bank: analogue/exposure/banding setup, CLKRC(0x11) = 0 (no XVCLK
 *     divider), the SVGA window;
 *   - DSP bank: HSIZE2/VSIZE2 (0xC0/0xC1) = 0xC8/0x96 -> an 800x600 input to
 *     the scaler, ZMOW/ZMOH/ZMHH (0x5A/0x5B/0x5C) = 0x50/0x3C/0x00 -> a 320x240
 *     output, R_DVP_SP (0xD3) = 0x08 -> the DVP clock divider, R_BYPASS (0x05)
 *     = 0 -> DSP enabled;
 *   - IMAGE_MODE (0xDA) is written TWICE: 0x08 (RGB565) and then 0x09, which
 *     adds bit 0 = DVP byte swap.  0x09 is what ST ships, so it is what this
 *     table keeps.  camera.c re-writes that one register afterwards from
 *     CAM_DVP_BYTE_SWAP -- the table itself stays
 *     byte-identical to upstream, because "known-good" is the only property it
 *     has that we cannot re-derive.
 */
